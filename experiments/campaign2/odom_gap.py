#!/usr/bin/env python3
"""Post-hoc check (not part of the frozen analysis): for the trials in which the
ground-truth distance to the goal at the end of the drive is above the 0.5 m
criterion although Nav2 reported SUCCEEDED, compare three end-of-drive positions:
the Gazebo ground truth, the AMCL pose that Nav2's goal checker uses (last
``amcl=`` of ``drive.log``), and the wheel odometry shifted to the start pose
(``odom_x``, ``odom_y`` of ``telemetry.csv`` plus the start).

The set of trials is read from ``results.json.gz``; nothing in it is edited.
Run from the repository root, in the environment of the campaign:

    python3 experiments/campaign2/odom_gap.py [--raw /mnt/d/wsl/se-mppi/campaign2]

It writes ``ODOM_GAP.json`` and ``ODOM_GAP.md`` next to this file. The paper quotes
the output verbatim (``scripts/check_paper_numbers.py`` re-reads ``ODOM_GAP.json``).
"""
import argparse
import csv
import gzip
import json
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
LINE = re.compile(r'\[basic_navigator\]: \[\s*([\d.]+)s\] dist=([\d.]+)m amcl=\(([-\d.]+),([-\d.]+) ')
STAMP = re.compile(r'^\[INFO\] \[([\d.]+)\]')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--raw', default='/mnt/d/wsl/se-mppi/campaign2')
    a = ap.parse_args()
    res = json.load(gzip.open(os.path.join(HERE, 'results.json.gz')))
    rows = []
    for t in res['trials']:
        if t['outcome'] != 'NOT_REACHED_ABORTED' or t.get('nav2_result') != 'SUCCEEDED':
            continue
        tdir = os.path.join(a.raw, 'trials', t['trial_id'])
        meta = json.load(open(os.path.join(tdir, 'meta.json')))
        start, goal = meta['start'], meta['goal']
        drive = open(os.path.join(tdir, 'drive.log')).read().splitlines()
        last = None
        for ln in drive:
            m = LINE.search(ln)
            if m:
                s = STAMP.match(ln)
                last = (float(s.group(1)), float(m.group(2)), float(m.group(3)), float(m.group(4)))
        wall, nav_dist, ax, ay = last
        tel = list(csv.DictReader(open(os.path.join(tdir, 'telemetry.csv'))))
        best = None
        for r in tel:
            try:
                w = float(r['wall_s'])
                gx, gy, ox, oy = (float(r[k]) for k in ('gt_x', 'gt_y', 'odom_x', 'odom_y'))
            except ValueError:
                continue
            if any(math.isnan(v) for v in (gx, gy, ox, oy)):
                continue
            if best is None or abs(w - wall) < abs(best[0] - wall):
                best = (w, gx, gy, ox + start[0], oy + start[1])
        _, gx, gy, ox, oy = best
        d = lambda x, y: math.hypot(x - goal[0], y - goal[1])
        rows.append({
            'trial': t['trial_id'],
            'final_gt_distance_m': round(t['final_goal_distance_m'], 3),
            'nav2_amcl_distance_m': round(nav_dist, 2),
            'odom_distance_m': round(d(ox, oy), 3),
            'odom_minus_gt_m': round(math.hypot(ox - gx, oy - gy), 3),
            'amcl_minus_gt_m': round(math.hypot(ax - gx, ay - gy), 3),
        })
    rows.sort(key=lambda r: r['trial'])
    out = {'n': len(rows), 'rows': rows}
    json.dump(out, open(os.path.join(HERE, 'ODOM_GAP.json'), 'w'), indent=1, sort_keys=True)
    lines = ['# Ground truth against the localization estimate at the end of the drive',
             '', 'Generated by `odom_gap.py` (post hoc, not frozen). Trials: Nav2 SUCCEEDED, '
             'ground-truth final distance above 0.5 m.', '',
             '| Trial | GT distance to goal (m) | Distance Nav2 printed from AMCL (m) | '
             'Shifted odometry distance (m) | Odometry vs GT (m) | AMCL vs GT (m) |',
             '|---|---|---|---|---|---|']
    for r in rows:
        lines.append(f"| {r['trial']} | {r['final_gt_distance_m']:.3f} | {r['nav2_amcl_distance_m']:.2f} | "
                     f"{r['odom_distance_m']:.3f} | {r['odom_minus_gt_m']:.3f} | {r['amcl_minus_gt_m']:.3f} |")
    open(os.path.join(HERE, 'ODOM_GAP.md'), 'w').write('\n'.join(lines) + '\n')
    print(len(rows), 'trials')


if __name__ == '__main__':
    main()
